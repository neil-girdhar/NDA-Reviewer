def _load_nda_knowledge() -> str:
    """
    Load synthesized historical NDA knowledge from nda_knowledge.json and
    format it as a compact prompt section.  Returns an empty string if the
    file is missing so the service degrades gracefully.
    """
    kb_path = Path(__file__).parent.parent / "nda_knowledge.json"
    if not kb_path.exists():
        return ""

    try:
        kb = json.loads(kb_path.read_text(encoding="utf-8"))
    except Exception:
        return ""

    lines = ["\n## Historical NDA Knowledge — Ascential Real Agreements\n",
             "The following intelligence was extracted from 211 signed Ascential historical NDAs. "
             "Use it to calibrate your analysis against what Ascential has actually agreed to in practice.\n"]

    # ── Ascential template verbatim language ──────────────────────────────
    tc = kb.get("ascential_template_clauses", {})
    if tc:
        lines.append("\n### Ascential's Own Standard Template — Verbatim Key Language\n")
        for key, val in tc.items():
            if key == "description" or not val or val.startswith("Not visible"):
                continue
            label = key.replace("_", " ").title()
            lines.append(f"**{label}:** {val}\n")

    # ── Common counterparty patterns ──────────────────────────────────────
    patterns = kb.get("common_counterparty_patterns", [])
    if patterns:
        lines.append("\n### Counterparty Patterns Ascential Has Accepted\n")
        for p in patterns:
            accepted = "✓ Ascential has signed" if p.get("ascential_accepted") else "⚠ Not confirmed accepted"
            lines.append(f"- **{p['pattern']}** ({accepted}): {p.get('notes', '')}\n")

    # ── Real red flags seen in signed agreements ──────────────────────────
    flags = kb.get("red_flags_seen_in_real_agreements", [])
    if flags:
        lines.append("\n### Real Red/Amber Flags Seen in Signed Ascential NDAs\n")
        for f in flags:
            lines.append(f"- **{f['clause_type']}**: {f['why_problematic']}\n")

    # ── Entity naming observations ─────────────────────────────────────────
    entity_obs = kb.get("entity_naming_observations", "")
    if entity_obs:
        lines.append(f"\n### Entity Naming — Observed in Real Agreements\n{entity_obs}\n")

    return "".join(lines)


