def _extract_json(text: str) -> str:
    """
    Best-effort extraction of a JSON array from Claude's response,
    handling markdown fences, leading prose, and trailing commentary.
    """
    text = text.strip()

    # Strip ```json ... ``` or ``` ... ``` fences
    fenced = re.search(r"```(?:json)?\s*([\s\S]*?)```", text)
    if fenced:
        return fenced.group(1).strip()

    # Find the outermost [...] array
    start = text.find("[")
    end = text.rfind("]")
    if start != -1 and end != -1 and end > start:
        return text[start : end + 1]

    return text


def _salvage_partial_json(text: str) -> list:
    """
    If the response was truncated mid-stream, recover every complete JSON
    object that was already closed before the cut-off point.
    """
    start = text.find("[")
    if start == -1:
        return []

    content = text[start + 1:]
    results = []
    depth = 0
    obj_start = None

    i = 0
    in_string = False
    escape_next = False

    while i < len(content):
        ch = content[i]

        if escape_next:
            escape_next = False
            i += 1
            continue

        if ch == "\\" and in_string:
            escape_next = True
            i += 1
            continue

        if ch == '"':
            in_string = not in_string
        elif not in_string:
            if ch == "{":
                if depth == 0:
                    obj_start = i
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0 and obj_start is not None:
                    fragment = content[obj_start : i + 1]
                    try:
                        results.append(json.loads(fragment))
                    except json.JSONDecodeError:
                        pass
                    obj_start = None
        i += 1

    return results


def _raise_friendly(e: Exception) -> None:
    if isinstance(e, RateLimitError):
        raise RuntimeError("Claude API rate limit reached — wait a moment and try again.") from e
    if isinstance(e, APITimeoutError):
        raise RuntimeError("Claude API timed out — the NDA may be too large; try again.") from e
    if isinstance(e, AuthenticationError):
        raise RuntimeError("Claude API authentication failed — check the ANTHROPIC_API_KEY setting.") from e
    if isinstance(e, APIConnectionError):
        raise RuntimeError("Could not reach the Claude API — check network connectivity.") from e
    raise RuntimeError(f"Claude API error: {e}") from e


_TRANSIENT = (RateLimitError, APITimeoutError, APIConnectionError)
_MAX_RETRIES = 3


def _is_transient(e: Exception) -> bool:
    """
    Return True for exceptions that are worth retrying.

    The Anthropic SDK wraps most network errors into its own types, but on
    Windows a mid-stream TCP reset ([WinError 10054]) can surface as a raw
    ConnectionResetError (OSError subclass) before the SDK gets a chance to
    wrap it.  We also check for httpx-level network errors (transitive dep).
    """
    if isinstance(e, _TRANSIENT):
        return True
    if isinstance(e, OSError):          # covers ConnectionResetError / WinError 10054
        return True
    try:
        import httpx
        if isinstance(e, (httpx.NetworkError, httpx.RemoteProtocolError)):
            return True
    except ImportError:
        pass
    return False


def _stream_with_retry(**kwargs) -> anthropic.types.Message:
    """Stream a Claude API call and retry on transient network/rate errors."""
    last_exc: Exception = RuntimeError("unknown")
    for attempt in range(_MAX_RETRIES):
        try:
            with _client.messages.stream(**kwargs) as stream:
                return stream.get_final_message()
        except Exception as e:
            if _is_transient(e):
                last_exc = e
                if attempt < _MAX_RETRIES - 1:
                    wait = 5 * (attempt + 1)   # 5 s, then 10 s
                    time.sleep(wait)
            else:
                _raise_friendly(e)
    _raise_friendly(last_exc)


def generate_clean_copy_text(raw_text: str, findings: List[dict]) -> str:
    """
    Ask Claude Opus 4.8 (with adaptive thinking) to rewrite the NDA with every
    Red and Amber issue fully resolved to a definitively GREEN standard.

    We always use the high-stakes model here because this is the final legal
    output — it must pass re-analysis with zero Red or Amber findings.
    Adaptive thinking gives Claude the reasoning depth to ensure each clause
    replacement is genuinely market-standard, not just nominally compliant.

    Returns the revised NDA as plain text (no markdown).
    """
    issues = [
        f for f in findings
        if f.get("rag_rating") in ("Red", "Amber") and f.get("replacement_language", "").strip()
    ]

    if not issues:
        return raw_text   # all Green — nothing to change

    changes_desc = "\n\n".join(
        f"CHANGE {i + 1}: [{f['rag_rating'].upper()} — {f['clause_type']}]\n"
        + (
            f"  Problematic text to replace: {f['suggested_redline']}\n"
            if f.get("suggested_redline")
            else "  (This clause is absent from the NDA — add it as a new section.)\n"
        )
        + f"  Replace with this exact language: {f['replacement_language']}"
        for i, f in enumerate(issues)
    )

    prompt = (
        "You are a senior NDA specialist at a top-tier US law firm editing a Non-Disclosure "
        "Agreement on behalf of Ascential Technologies (the Receiving Party / vendor). "
        "Your task is to produce a FINAL CLEAN COPY with every listed change applied.\n\n"

        f"ORIGINAL NDA:\n\n{raw_text}\n\n"
        "---\n\n"
        f"REQUIRED CHANGES ({len(issues)} total — apply EVERY one):\n\n"
        f"{changes_desc}\n\n"
        "---\n\n"
        "EDITING RULES — follow these exactly:\n"
        "1. Apply every change listed above — do not skip any.\n"
        "2. For each change, locate the problematic text in the original NDA "
        "   (use the 'Problematic text to replace' field to find it — exact or substantially "
        "   similar phrasing) and replace it with the EXACT text in the "
        "   'Replace with this exact language' field. "
        "   Do NOT paraphrase, improve, or supplement the replacement language. "
        "   The user has already reviewed and approved it — reproduce it word for word.\n"
        "3. For absent clauses (marked 'This clause is absent'), insert the provided "
        "   replacement text as a new clearly titled section before Governing Law or at the end.\n"
        "4. Copy ALL other clauses VERBATIM — do not rephrase, summarise, or omit any text "
        "   that is not being changed.\n"
        "5. Preserve all original section headings, numbering, and document structure.\n"
        "6. Return ONLY the complete revised NDA text — no preamble, no closing commentary, "
        "   no explanations, no markdown (no **, no ##, no ```).\n"
    )

    # Use streaming to prevent HTTP timeouts on large documents; retries once on transient errors
    response = _stream_with_retry(
        model=settings.high_stakes_model,
        max_tokens=16000,
        thinking={"type": "adaptive"},
        messages=[{"role": "user", "content": prompt}],
    )

    # Extract the text block (adaptive thinking also produces a thinking block)
    result = next(
        (block.text for block in response.content if block.type == "text"),
        ""
    ).strip()

    # Strip markdown fences if Claude added them despite instructions
    if result.startswith("```"):
        result = re.sub(r"^```[^\n]*\n?", "", result)
        result = re.sub(r"\n?```\s*$", "", result)

    return result.strip()


def analyse_nda(raw_text: str, clauses: List[dict]) -> List[dict]:
    """
    Send NDA text to Claude Opus 4.8 with adaptive thinking and maximum effort.

    Always uses the high-stakes model — there is no "standard" path any more.
    Adaptive thinking lets the model reason through ambiguous clause language
    before committing to a RAG rating. effort="xhigh" maximises depth on
    complex multi-clause NDAs. Streaming prevents HTTP timeouts on large docs.
    Prompt caching keeps costs reasonable on repeat uploads of the same NDA.
    """
    clauses_text = "\n\n".join(
        f"[CLAUSE: {c['heading']}]\n{c['body']}" for c in clauses
    )

    # Use streaming + get_final_message() to prevent timeouts on large NDAs; retries once on transient errors
    # max_tokens=128000: xhigh-effort adaptive thinking can consume significant tokens for reasoning;
    # large NDAs with many clauses need substantial token budget for complete JSON output.
    # Setting to 128k to ensure even the largest NDAs get fully analyzed.
    response = _stream_with_retry(
        model=settings.high_stakes_model,
        max_tokens=128000,
        thinking={"type": "adaptive"},
        output_config={"effort": "xhigh"},
        system=[
            {
                "type": "text",
                "text": _SYSTEM_PROMPT,
                "cache_control": {"type": "ephemeral"},
            }
        ],
        messages=[
            {
                "role": "user",
                "content": [
                    {
                        "type": "text",
                        "text": f"Full NDA text for context:\n\n{raw_text}",
                        "cache_control": {"type": "ephemeral"},
                    },
                    {
                        "type": "text",
                        "text": (
                            f"Analyze these extracted clauses and return ONLY the JSON array:\n\n"
                            f"{clauses_text}"
                        ),
                    },
                ],
            }
        ],
    )

    # Extract text block — adaptive thinking also emits a thinking block
    raw = next(
        (block.text for block in response.content if block.type == "text"),
        ""
    )

    if not raw.strip():
        # No text block means all tokens were consumed by thinking — increase max_tokens or reduce effort.
        raise ValueError(
            "Claude returned no text output (response contained only a thinking block). "
            "The model likely exhausted the token budget on reasoning. Retry the analysis."
        )

    cleaned = _extract_json(raw)

    try:
        return json.loads(cleaned)
    except json.JSONDecodeError:
        # Response was truncated — recover every complete object we can
        salvaged = _salvage_partial_json(raw)
        if salvaged:
            warning = {
                "clause_type": "Analysis Warning",
                "rag_rating": "Amber",
                "plain_english_summary": (
                    f"Claude's response was truncated — {len(salvaged)} clause(s) were recovered "
                    f"but the full NDA may not have been reviewed. Re-run the analysis to confirm."
                ),
                "risk_reason": "Incomplete analysis due to response truncation. Some clauses may be missing from this review.",
                "suggested_redline": "",
                "replacement_language": "",
                "negotiation_talking_points": "",
            }
            return [warning] + salvaged
        # Nothing usable — surface a clear message rather than a raw JSONDecodeError
        preview = raw[:120].replace("\n", " ")
        raise ValueError(
            f"Claude response was not valid JSON and could not be salvaged. "
            f"Response started with: {preview!r}"
        ) from None
